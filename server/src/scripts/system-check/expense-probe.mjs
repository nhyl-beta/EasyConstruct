import { chromium } from "playwright";
const WEB = "http://localhost:5173";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--no-sandbox"] });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const writes = [];
p.on("response", async (r) => { const u = r.url(); if (u.includes("/api/") && r.request().method() !== "GET") writes.push(`${r.request().method()} ${u.replace(/^https?:\/\/[^/]+/, "")} ${r.status()} ${r.status()>=400 ? (await r.text().catch(()=>"")).slice(0,160) : ""}`); });
await p.goto(`${WEB}/login`); await p.fill("#email", "finance@easyconstruct.demo"); await p.fill("#password", "Demo@12345"); await p.click("button:has-text('Sign in')"); await p.waitForTimeout(3000);
await p.goto(`${WEB}/expenses`, { waitUntil: "domcontentloaded" }); await p.waitForTimeout(2500);
const before = (await p.innerText("body")).includes("UI Check Vendor");
await p.getByRole("button", { name: "Record expense" }).first().click(); await p.waitForTimeout(700);
const dlg = p.locator("[role=dialog]");
const pickFirst = async (opener) => { await opener.click(); await p.waitForTimeout(400); await p.locator("[role=option]:visible, [cmdk-item]:visible").first().click(); await p.waitForTimeout(400); };
await dlg.getByRole("combobox").first().click(); await p.waitForTimeout(400);
await p.getByRole("option", { name: /Add new vendor/ }).click(); await p.waitForTimeout(400);
await dlg.getByPlaceholder("New vendor name").fill("UI Check Vendor");
await dlg.getByRole("button", { name: "Add", exact: true }).click(); await p.waitForTimeout(1200);
console.log("after vendor add:", (await dlg.innerText()).replace(/\n+/g, " | ").slice(0, 200));
const combos = dlg.getByRole("combobox");
console.log("comboboxes:", await combos.count());
await pickFirst(combos.nth(1));
await pickFirst(combos.nth(2));
await dlg.locator("input[type=number]").fill("2500");
const btn = dlg.getByRole("button", { name: "Record expense", exact: true });
console.log("submit disabled:", await btn.isDisabled());
await btn.click(); await p.waitForTimeout(2500);
console.log("writes:", writes);
console.log("dialog closed:", (await p.locator("[role=dialog]:visible").count()) === 0);
await p.reload({ waitUntil: "domcontentloaded" }); await p.waitForTimeout(2500);
const txt = await p.innerText("body");
console.log("vendor visible in list before/after:", before, txt.includes("UI Check Vendor"), "| 2,500 shown:", /2,500/.test(txt));
await b.close();
